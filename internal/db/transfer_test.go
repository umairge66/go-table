// transferEngines returns a source and an empty target session for every
// available engine, both pointing at different schemas/databases.
func transferEngines(t *testing.T) map[string][2]*Conn {
	out := map[string][2]*Conn{}
	ctx := context.Background()
	dir := t.TempDir()
	src := model.NewConnection(model.DriverSQLite)
	src.Name, src.Path = "src", filepath.Join(dir, "src.db")
	dst := *src
	dst.Path = filepath.Join(dir, "dst.db")
	out["sqlite"] = [2]*Conn{openTest(t, src, ""), openTest(t, &dst, "")}

	for _, e := range []struct {
		env string
		d   model.Driver
	}{{"PG", model.DriverPostgres}, {"MYSQL", model.DriverMySQL}, {"MARIADB", model.DriverMariaDB}} {
		cfg, pw := serverConfigOptional(e.env, e.d)
		if cfg == nil {
			continue
		}
		a := openTest(t, cfg, pw)
		b := openTest(t, cfg, pw)
		if e.d == model.DriverPostgres {
			for _, s := range []string{"DROP SCHEMA IF EXISTS gt_src CASCADE", "DROP SCHEMA IF EXISTS gt_dst CASCADE", "CREATE SCHEMA gt_src", "CREATE SCHEMA gt_dst"} {
				mustExec(t, a, s)
			}
			a.UseSchema(ctx, "gt_src")
			b.UseSchema(ctx, "gt_dst")
		} else {
			for _, s := range []string{"DROP DATABASE IF EXISTS gt_src", "DROP DATABASE IF EXISTS gt_dst", "CREATE DATABASE gt_src", "CREATE DATABASE gt_dst"} {
				mustExec(t, a, s)
			}
			a.UseSchema(ctx, "gt_src")
			b.UseSchema(ctx, "gt_dst")
		}
		out[string(e.d)] = [2]*Conn{a, b}
	}
	return out
}

func mustExec(t *testing.T, c *Conn, s string) {
	t.Helper()
	if _, err := c.Exec(context.Background(), s); err != nil {
		t.Fatalf("%s: %v", s, err)
	}
}

func queryOne(t *testing.T, c *Conn, q string) []Value {
	t.Helper()
	res, err := c.Execute(context.Background(), q, 0)
	if err != nil || res[0].Err != nil || len(res[0].Set.Rows) == 0 {
		t.Fatalf("%s: %v %+v", q, err, res)
	}
	return res[0].Set.Rows[0]
}

