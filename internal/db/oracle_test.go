// TestOracle covers GoTable on Oracle. It has its own test as Oracle keeps
// unquoted names in upper case, commits DDL by itself and has no BEGIN
// statement, all of which the shared suite's SQL assumes otherwise.
func TestOracle(t *testing.T) {
	cfg, pw := serverConfig(t, "ORACLE", model.DriverOracle)
	c := openTest(t, cfg, pw)
	ctx, cancel := context.WithTimeout(context.Background(), 4*time.Minute)
	defer cancel()
	exec := func(q string) Result {
		t.Helper()
		res, err := c.Execute(ctx, q, 0)
		if err != nil {
			t.Fatalf("%s: %v", q, err)
		}
		return res[len(res)-1]
	}
	must := func(q string) {
		t.Helper()
		if r := exec(q); r.Err != nil {
			t.Fatalf("%s: %v", q, r.Err)
		}
	}
	quiet := func(q string) { c.Execute(context.Background(), q, 0) }
	schema := c.Schema()
	tbl := TableRef{Schema: schema, Name: "GT_PEOPLE"}
	for _, q := range []string{"DROP VIEW GT_PEOPLE_VIEW", "DROP TABLE GT_CHILD CASCADE CONSTRAINTS", "DROP TABLE GT_PEOPLE CASCADE CONSTRAINTS",
		"DROP TABLE GT_MADE CASCADE CONSTRAINTS", "DROP TABLE GT_PEOPLE2 CASCADE CONSTRAINTS"} {
		quiet(q)
	}
	must(`CREATE TABLE gt_people (id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR2(100) NOT NULL,
		city VARCHAR2(100), score NUMBER(5) DEFAULT 0, seen DATE)`)
	must("COMMENT ON TABLE gt_people IS 'people'")
	must("COMMENT ON COLUMN gt_people.score IS 'points'")
	must("CREATE INDEX gt_people_city_idx ON gt_people (city)")
	// One INSERT per row: INSERT ALL would give them all the same identity.
	must(`INSERT INTO gt_people (name, city, score, seen) VALUES ('Alice', 'Berlin', 90, TIMESTAMP '2024-03-15 10:20:30');
		INSERT INTO gt_people (name, city, score) VALUES ('Bob', 'Paris', 70);
		INSERT INTO gt_people (name, city, score) VALUES ('Carol', NULL, 85);
		INSERT INTO gt_people (name, city, score) VALUES ('Dave', 'Berlin', 60);
		INSERT INTO gt_people (name, city, score) VALUES ('Eve_x', 'Rome', 99)`)
	must("CREATE VIEW gt_people_view AS SELECT name, score FROM gt_people")
	defer func() {
		for _, q := range []string{"DROP VIEW GT_PEOPLE_VIEW", "DROP TABLE GT_CHILD CASCADE CONSTRAINTS", "DROP TABLE GT_PEOPLE CASCADE CONSTRAINTS",
			"DROP TABLE GT_MADE CASCADE CONSTRAINTS", "DROP TABLE GT_PEOPLE2 CASCADE CONSTRAINTS"} {
			quiet(q)
		}
	}()

	t.Run("catalog", func(t *testing.T) {
		if v, err := c.ServerVersion(ctx); err != nil || !strings.HasPrefix(v, "Oracle ") {
			t.Errorf("version %q %v", v, err)
		}
		if s, _ := c.Schemas(ctx); !slices.Contains(s, schema) || slices.Contains(s, "SYS") {
			t.Errorf("schemas %v (current %s)", s, schema)
		}
		objs, err := c.Objects(ctx, schema)
		if err != nil {
			t.Fatal(err)
		}
		kinds := map[string]ObjectKind{}
		for _, o := range objs {
			kinds[o.Name] = o.Kind
		}
		if kinds["GT_PEOPLE"] != KindTable || kinds["GT_PEOPLE_VIEW"] != KindView {
			t.Errorf("objects %v", kinds)
		}
		cols, err := c.Columns(ctx, tbl)
		if err != nil || len(cols) != 5 {
			t.Fatalf("columns %+v %v", cols, err)
		}
		if !cols[0].PrimaryKey || !cols[0].AutoIncrement || cols[0].Default != nil || cols[1].Type != "VARCHAR2(100)" || cols[1].Nullable {
			t.Errorf("id/name %+v %+v", cols[0], cols[1])
		}
		if cols[3].Type != "NUMBER(5)" || cols[3].DefaultKind != DefaultValue || cols[3].DefaultText != "0" || cols[3].Comment != "points" {
			t.Errorf("score %+v", cols[3])
		}
		idx, err := c.Indexes(ctx, tbl)
		if err != nil || len(idx) != 2 || !idx[0].Primary || idx[1].Name != "GT_PEOPLE_CITY_IDX" || !slices.Equal(idx[1].Columns, []string{"CITY"}) {
			t.Errorf("indexes %+v %v", idx, err)
		}
		info, err := c.TableInfo(ctx, tbl)
		if err != nil || info.Comment != "people" || len(info.Checks) != 0 {
			t.Errorf("info %+v %v (NOT NULL checks must not show)", info, err)
		}
		ddl, err := c.Definition(ctx, Object{Schema: schema, Name: "GT_PEOPLE", Kind: KindTable})
		if err != nil || !strings.Contains(ddl, "CREATE TABLE") || strings.Contains(ddl, "STORAGE(") {
			t.Errorf("definition %q %v", ddl, err)
		}
		if v, err := c.Definition(ctx, Object{Schema: schema, Name: "GT_PEOPLE_VIEW", Kind: KindView}); err != nil || !strings.Contains(strings.ToUpper(v), "VIEW") {
			t.Errorf("view %q %v", v, err)
		}
	})

	cols := []string{"ID", "NAME", "CITY", "SCORE", "SEEN"}
	t.Run("browse and filter", func(t *testing.T) {
		rs, err := c.FetchRows(ctx, tbl, Page{Sort: []Sort{{Column: "SCORE", Dir: Desc}}, Limit: 2, Offset: 1}, cols)
		if err != nil || !slices.Equal(names(rs, 1), []string{"Alice", "Carol"}) {
			t.Fatalf("page %v %v", rs, err)
		}
		if rs, _ := c.FetchRows(ctx, tbl, Page{Filters: []Filter{{Column: "NAME", Op: OpEq, Value: "Alice"}}}, cols); len(rs.Rows) != 1 || rs.Rows[0][4].Text != "2024-03-15 10:20:30" {
			t.Errorf("DATE keeps its time: %+v", rs.Rows)
		}
		for _, tc := range []struct {
			f    Filter
			want []string
		}{
			{Filter{Column: "CITY", Op: OpEq, Value: "Berlin"}, []string{"Alice", "Dave"}},
			{Filter{Column: "SCORE", Op: OpGt, Value: "85"}, []string{"Alice", "Eve_x"}},
			{Filter{Column: "CITY", Op: OpIn, Value: "Paris, Rome"}, []string{"Bob", "Eve_x"}},
			{Filter{Column: "CITY", Op: OpIsNull}, []string{"Carol"}},
			{Filter{Column: "SCORE", Op: OpBetween, Value: "60", Value2: "85"}, []string{"Bob", "Carol", "Dave"}},
			{Filter{Column: "NAME", Op: OpContains, Value: "AR"}, []string{"Carol"}},
			{Filter{Column: "NAME", Op: OpContains, Value: "_"}, []string{"Eve_x"}},
			{Filter{Column: "NAME", Op: OpBeginsWith, Value: "da"}, []string{"Dave"}},
			{Filter{Column: "SCORE", Op: OpLike, Value: "9%"}, []string{"Alice", "Eve_x"}},
			{Filter{Column: AnyColumn, Op: OpContains, Value: "rom"}, []string{"Eve_x"}},
		} {
			p := Page{Filters: []Filter{tc.f}, Sort: []Sort{{Column: "NAME"}}}
			rs, err := c.FetchRows(ctx, tbl, p, cols)
			if err != nil || !slices.Equal(names(rs, 1), tc.want) {
				t.Errorf("%+v: %v %v", tc.f, names(rs, 1), err)
			}
			if n, err := c.CountRows(ctx, tbl, p, cols); err != nil || n != int64(len(tc.want)) {
				t.Errorf("%+v: count %d %v", tc.f, n, err)
			}
		}
	})

	t.Run("edit rows", func(t *testing.T) {
		err := c.ApplyChanges(ctx, tbl, []Change{
			{Kind: ChangeUpdate, Key: map[string]Value{"ID": Text("1")}, Values: map[string]Value{"CITY": Text("Munich"), "SCORE": Text("91"), "SEEN": Text("2024-04-01 08:00:00")}},
			{Kind: ChangeUpdate, Key: map[string]Value{"ID": Text("2")}, Values: map[string]Value{"CITY": NullValue}},
			{Kind: ChangeInsert, Values: map[string]Value{"NAME": Text("Frank 'O"), "CITY": Text(`C:\x`)}},
			{Kind: ChangeDelete, Key: map[string]Value{"ID": Text("4")}},
		}, true)
		if err != nil {
			t.Fatal(err)
		}
		rs, _ := c.FetchRows(ctx, tbl, Page{Sort: []Sort{{Column: "ID"}}}, cols)
		got := map[string][]Value{}
		for _, r := range rs.Rows {
			got[r[1].Text] = r
		}
		if a := got["Alice"]; a[2].Text != "Munich" || a[3].Text != "91" || a[4].Text != "2024-04-01 08:00:00" {
			t.Errorf("Alice %+v", a)
		}
		if f, ok := got["Frank 'O"]; !ok || f[2].Text != `C:\x` || f[3].Text != "0" {
			t.Errorf("Frank %+v", f)
		}
		if _, ok := got["Dave"]; ok || !got["Bob"][2].Null {
			t.Errorf("delete / NULL: %v", got)
		}
		// A failing change rolls the others back.
		err = c.ApplyChanges(ctx, tbl, []Change{
			{Kind: ChangeUpdate, Key: map[string]Value{"ID": Text("1")}, Values: map[string]Value{"CITY": Text("Hamburg")}},
			{Kind: ChangeUpdate, Key: map[string]Value{"ID": Text("999")}, Values: map[string]Value{"CITY": Text("x")}},
		}, true)
		if err == nil || !strings.Contains(err.Error(), "999") {
			t.Fatalf("expected the failing statement: %v", err)
		}
		if rs, _ := c.FetchRows(ctx, tbl, Page{Filters: []Filter{{Column: "ID", Op: OpEq, Value: "1"}}}, cols); rs.Rows[0][2].Text != "Munich" {
			t.Errorf("not rolled back: %+v", rs.Rows[0])
		}
		if err := c.ApplyChanges(ctx, tbl, []Change{{Kind: ChangeInsert}}, true); err == nil {
			t.Error("an insert without values should be refused")
		}
	})

	t.Run("sql editor", func(t *testing.T) {
		script := "-- a; comment\nSELECT COUNT(*) AS n FROM gt_people;\nBEGIN\n  UPDATE gt_people SET score = score + 1 WHERE name = 'it''s;fine';\nEND;\n/\nSELECT name FROM gt_people WHERE id = 1"
		res, err := c.Execute(ctx, script, 0)
		if err != nil || len(res) != 3 {
			t.Fatalf("%v %+v", err, res)
		}
		for _, r := range res {
			if r.Err != nil {
				t.Fatalf("%s: %v", r.Statement, r.Err)
			}
		}
		if res[0].Set.Columns[0] != "N" || res[0].Set.Rows[0][0].Text != "5" || res[2].Set.Rows[0][0].Text != "Alice" {
			t.Errorf("results %+v %+v", res[0].Set, res[2].Set)
		}
		if res, _ := c.Execute(ctx, "SELECT * FROM gt_people", 2); !res[0].Truncated {
			t.Error("row cap")
		}
		if res, _ := c.Execute(ctx, "SELECT 1 FROM dual; SELECT * FROM gt_missing; SELECT 2 FROM dual", 0); len(res) != 2 || res[1].Err == nil {
			t.Errorf("stops at the error: %+v", res)
		}
	})

	t.Run("structure", func(t *testing.T) {
		apply := func(tb TableRef, ops ...AlterOp) {
			t.Helper()
			if stmts, err := c.Alter(ctx, tb, ops, false); err != nil {
				t.Fatalf("%v: %v", stmts, err)
			}
		}
		col := func(n string) Column {
			t.Helper()
			cols, _ := c.Columns(ctx, tbl)
			for _, cl := range cols {
				if cl.Name == n {
					return cl
				}
			}
			t.Fatalf("no column %s", n)
			return Column{}
		}
		apply(tbl, AlterOp{Kind: AlterAddColumn, Def: &ColumnDef{Name: "NOTE", Type: "VARCHAR2(20)", Nullable: false, DefaultKind: DefaultValue, Default: "it's", Comment: "free"}})
		if n := col("NOTE"); n.Nullable || n.DefaultText != "it's" || n.Comment != "free" {
			t.Errorf("note %+v", n)
		}
		apply(tbl, AlterOp{Kind: AlterModifyColumn, Column: "SCORE", Def: &ColumnDef{Name: "POINTS", Type: "NUMBER(8)", Nullable: false, DefaultKind: DefaultValue, Default: "1", Comment: "pts"}})
		if p := col("POINTS"); p.Type != "NUMBER(8)" || p.Nullable || p.DefaultText != "1" || p.Comment != "pts" {
			t.Errorf("points %+v", p)
		}
		apply(tbl, AlterOp{Kind: AlterModifyColumn, Column: "POINTS", Def: &ColumnDef{Name: "POINTS", Type: "NUMBER(8)", Nullable: true, Comment: "pts"}})
		if p := col("POINTS"); !p.Nullable || p.Default != nil {
			t.Errorf("points nullable, no default %+v", p)
		}
		apply(tbl, AlterOp{Kind: AlterAddIndex, Index: &IndexDef{Name: "GT_NAME_UQ", Columns: []string{"NAME"}, Unique: true}})
		apply(tbl, AlterOp{Kind: AlterRenameIndex, Name: "GT_NAME_UQ", NewName: "GT_NAME_UQ2"})
		if x, ok := findIndex(mustState(t, c, tbl), "GT_NAME_UQ2"); !ok || !x.Unique {
			t.Errorf("renamed index %+v", x)
		}
		apply(tbl, AlterOp{Kind: AlterDropIndex, Name: "GT_NAME_UQ2"})
		apply(tbl, AlterOp{Kind: AlterSetPrimaryKey, Columns: []string{"ID", "NAME"}})
		if pk, _ := primaryIndex(mustState(t, c, tbl)); !slices.Equal(pk.Columns, []string{"ID", "NAME"}) {
			t.Errorf("primary key %v", pk.Columns)
		}
		apply(tbl, AlterOp{Kind: AlterSetPrimaryKey, Columns: []string{"ID"}})

		must("CREATE TABLE gt_child (id NUMBER PRIMARY KEY, person_id NUMBER)")
		must("INSERT INTO gt_child VALUES (1, 1)")
		child := TableRef{Schema: schema, Name: "GT_CHILD"}
		if _, err := c.Alter(ctx, child, []AlterOp{{Kind: AlterAddForeignKey, ForeignKey: &ForeignKeyDef{Columns: []string{"PERSON_ID"},
			RefTable: "GT_PEOPLE", RefColumns: []string{"ID"}, OnUpdate: "CASCADE"}}}, false); err == nil {
			t.Error("ON UPDATE CASCADE should be refused")
		}
		apply(child, AlterOp{Kind: AlterAddForeignKey, ForeignKey: &ForeignKeyDef{Name: "GT_CHILD_FK", Columns: []string{"PERSON_ID"},
			RefTable: "GT_PEOPLE", RefColumns: []string{"ID"}, OnDelete: "CASCADE"}})
		if fks := mustState(t, c, child).ForeignKeys; len(fks) != 1 || fks[0].Table != "GT_PEOPLE" || fks[0].OnDelete != "CASCADE" {
			t.Errorf("foreign keys %+v", fks)
		}
		apply(child, AlterOp{Kind: AlterDropForeignKey, Name: "GT_CHILD_FK"})

		apply(tbl, AlterOp{Kind: AlterAddCheck, Check: &CheckDef{Name: "GT_POINTS_CK", Expression: "points >= 0"}})
		if r := exec("INSERT INTO gt_people (name, points) VALUES ('neg', -1)"); r.Err == nil {
			t.Error("CHECK let -1 in")
		}
		if ck := mustState(t, c, tbl).Info.Checks; len(ck) != 1 || ck[0].Name != "GT_POINTS_CK" {
			t.Errorf("checks %+v", ck)
		}
		apply(tbl, AlterOp{Kind: AlterDropCheck, Name: "GT_POINTS_CK"})
		apply(tbl, AlterOp{Kind: AlterTableComment, Comment: "folks"})
		apply(tbl, AlterOp{Kind: AlterAddIndex, Index: &IndexDef{Columns: []string{"NOTE"}}})
		apply(tbl, AlterOp{Kind: AlterDropColumn, Column: "NOTE"})
		apply(tbl, AlterOp{Kind: AlterRenameTable, NewName: "GT_PEOPLE2"})
		apply(TableRef{Schema: schema, Name: "GT_PEOPLE2"}, AlterOp{Kind: AlterRenameTable, NewName: "GT_PEOPLE"})
		if info, _ := c.TableInfo(ctx, tbl); info.Comment != "folks" {
			t.Errorf("comment %q", info.Comment)
		}
		apply(child, AlterOp{Kind: AlterTruncate})
	})

	t.Run("create, import and dump", func(t *testing.T) {
		nt := NewTable{Name: "GT_MADE", Comment: "made", Columns: []NewColumn{
			{ColumnDef: ColumnDef{Name: "ID", Type: "NUMBER"}, PrimaryKey: true, AutoIncrement: true},
			{ColumnDef: ColumnDef{Name: "LABEL", Type: "VARCHAR2(40)", DefaultKind: DefaultValue, Default: "none", Comment: "l"}, Index: "unique"},
			{ColumnDef: ColumnDef{Name: "CITY", Type: "VARCHAR2(40)", Nullable: true}, Index: "index"},
		}}
		if _, err := c.CreateTable(ctx, schema, nt); err != nil {
			t.Fatal(err)
		}
		made := TableRef{Schema: schema, Name: "GT_MADE"}
		n, err := c.ImportCSV(ctx, strings.NewReader("label,city\na,Berlin\nb,\nc,Rome\n"), made,
			CSVImportOptions{Header: true, Columns: []string{"LABEL", "CITY"}, Mapping: []int{0, 1}, EmptyAsNull: true}, nil)
		if err != nil || n != 3 {
			t.Fatalf("csv %d %v", n, err)
		}
		rs, _ := c.FetchRows(ctx, made, Page{Sort: []Sort{{Column: "ID"}}}, nil)
		if len(rs.Rows) != 3 || rs.Rows[0][0].Text != "1" || rs.Rows[2][0].Text != "3" || !rs.Rows[1][2].Null {
			t.Errorf("identity ids / NULL: %+v", rs.Rows)
		}
		if _, err := c.CreateDatabase(ctx, NewDatabase{Name: "x"}); err == nil {
			t.Error("CREATE DATABASE should be refused")
		}

		var buf bytes.Buffer
		if err := c.Dump(ctx, &buf, DumpOptions{Objects: []Object{{Schema: schema, Name: "GT_MADE", Kind: KindTable}}, Structure: true, Data: true}, nil); err != nil {
			t.Fatal(err)
		}
		dump := buf.String()
		if !strings.Contains(dump, "CREATE TABLE") || !strings.Contains(dump, "INSERT ALL") || strings.Contains(dump, `"`+schema+`".`) {
			t.Errorf("dump:\n%s", dump)
		}
		must("DROP TABLE GT_MADE CASCADE CONSTRAINTS")
		if _, err := c.ImportSQL(ctx, strings.NewReader(dump), ImportOptions{}, nil); err != nil {
			t.Fatalf("import: %v\n%s", err, dump)
		}
		if n, err := c.CountRows(ctx, made, Page{}, nil); err != nil || n != 3 {
			t.Errorf("after import %d %v", n, err)
		}
	})

	t.Run("drop", func(t *testing.T) {
		must("ALTER TABLE gt_child ADD CONSTRAINT gt_child_fk2 FOREIGN KEY (person_id) REFERENCES gt_people (id)")
		stmts, err := c.Drop(ctx, []Object{{Schema: schema, Name: "GT_PEOPLE_VIEW", Kind: KindView}, {Schema: schema, Name: "GT_PEOPLE", Kind: KindTable}}, true)
		if err != nil || !strings.Contains(strings.Join(stmts, " "), "CASCADE CONSTRAINTS") {
			t.Fatalf("%v %v", stmts, err)
		}
		if fks, _ := c.ForeignKeys(ctx, TableRef{Schema: schema, Name: "GT_CHILD"}); len(fks) != 0 {
			t.Errorf("the child's key should be gone: %+v", fks)
		}
	})
}

func mustState(t *testing.T, c *Conn, tb TableRef) TableState {
	t.Helper()
	if err := c.lock(context.Background()); err != nil {
		t.Fatal(err)
	}
	defer c.mu.Unlock()
	st, err := c.loadTableState(context.Background(), tb)
	if err != nil {
		t.Fatal(err)
	}
	return st
}
