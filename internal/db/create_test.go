func col(name, typ string, opts ...func(*NewColumn)) NewColumn {
	c := NewColumn{ColumnDef: ColumnDef{Name: name, Type: typ, Nullable: true}}
	for _, o := range opts {
		o(&c)
	}
	return c
}

var (
	pk      = func(c *NewColumn) { c.PrimaryKey = true; c.Nullable = false }
	auto    = func(c *NewColumn) { c.AutoIncrement = true }
	notNull = func(c *NewColumn) { c.Nullable = false }
)

func TestBuildCreateTable(t *testing.T) {
	cols := []NewColumn{
		col("id", "integer", pk, auto),
		col("name", "text", notNull, func(c *NewColumn) { c.Comment = "who" }),
		col("created", "timestamp", func(c *NewColumn) { c.DefaultKind = DefaultExpression; c.Default = "CURRENT_TIMESTAMP" }),
		col("status", "varchar(20)", func(c *NewColumn) { c.DefaultKind = DefaultValue; c.Default = "new's" }),
	}
	pg, _ := BuildCreateTable(Dialect{kind: model.DriverPostgres}, "public", NewTable{Name: "people", Columns: cols, Comment: "all of them"})
	want := `CREATE TABLE "public"."people" (
  "id" integer NOT NULL GENERATED BY DEFAULT AS IDENTITY,
  "name" text NOT NULL,
  "created" timestamp DEFAULT CURRENT_TIMESTAMP,
  "status" varchar(20) DEFAULT 'new''s',
  PRIMARY KEY ("id")
);`
	if len(pg) != 3 || pg[0] != want || pg[1] != `COMMENT ON TABLE "public"."people" IS 'all of them';` || pg[2] != `COMMENT ON COLUMN "public"."people"."name" IS 'who';` {
		t.Fatalf("postgres:\n%s", strings.Join(pg, "\n"))
	}

	my, err := BuildCreateTable(Dialect{kind: model.DriverMySQL}, "shop", NewTable{Name: "people", Columns: cols, Comment: "all"})
	if err != nil || len(my) != 1 || !strings.Contains(my[0], "`id` integer NOT NULL AUTO_INCREMENT,") ||
		!strings.Contains(my[0], "`name` text NOT NULL COMMENT 'who'") || !strings.HasSuffix(my[0], ") COMMENT='all';") {
		t.Fatalf("mysql %v:\n%s", err, strings.Join(my, "\n"))
	}

	lite := []NewColumn{col("id", "INTEGER", pk, auto), col("n", "text", notNull),
		col("at", "text", func(c *NewColumn) { c.DefaultKind = DefaultExpression; c.Default = "datetime('now')" })}
	sq, err := BuildCreateTable(Dialect{kind: model.DriverSQLite}, "main", NewTable{Name: "t", Columns: lite})
	if err != nil || sq[0] != "CREATE TABLE \"t\" (\n  \"id\" INTEGER PRIMARY KEY AUTOINCREMENT NOT NULL,\n  \"n\" text NOT NULL,\n  \"at\" text DEFAULT (datetime('now'))\n);" {
		t.Fatalf("sqlite %v:\n%s", err, strings.Join(sq, "\n"))
	}

	// Composite primary key.
	two, _ := BuildCreateTable(Dialect{kind: model.DriverPostgres}, "public", NewTable{Name: "t", Columns: []NewColumn{col("a", "int", pk), col("b", "int", pk)}})
	if !strings.Contains(two[0], `PRIMARY KEY ("a", "b")`) {
		t.Fatalf("composite: %s", two[0])
	}

	bad := []struct {
		d    model.Driver
		t    NewTable
		want string
	}{
		{model.DriverPostgres, NewTable{Name: " ", Columns: cols}, "table name is required"},
		{model.DriverPostgres, NewTable{Name: "t"}, "at least one column"},
		{model.DriverPostgres, NewTable{Name: "t", Columns: []NewColumn{col("a", "int"), col("A", "int")}}, "appears twice"},
		{model.DriverPostgres, NewTable{Name: "t", Columns: []NewColumn{col("a", "text", auto)}}, "integer type"},
		{model.DriverPostgres, NewTable{Name: "t", Columns: []NewColumn{col("a", "int", auto), col("b", "int", auto)}}, "only one column"},
		{model.DriverMySQL, NewTable{Name: "t", Columns: []NewColumn{col("a", "int", auto)}}, "must be the primary key"},
		{model.DriverSQLite, NewTable{Name: "t", Columns: []NewColumn{col("a", "bigint", pk, auto)}}, "single INTEGER primary key"},
		{model.DriverSQLite, NewTable{Name: "t", Columns: []NewColumn{col("a", "int")}, Comment: "x"}, "table comments"},
		{model.DriverPostgres, NewTable{Name: "t", Columns: []NewColumn{col("a", "int; DROP")}}, "doesn't look like a column type"},
	}
	for _, b := range bad {
		if _, err := BuildCreateTable(Dialect{kind: b.d}, "s", b.t); err == nil || !strings.Contains(err.Error(), b.want) {
			t.Errorf("%s %+v: got %v, want %q", b.d, b.t, err, b.want)
		}
	}
}

func TestBuildCreateTableIndexesAndOptions(t *testing.T) {
	cols := []NewColumn{
		col("id", "int unsigned", pk, auto),
		col("email", "varchar(190)", notNull, func(c *NewColumn) { c.Index = "unique"; c.Collation = "utf8mb4_bin" }),
		col("city", "varchar(80)", func(c *NewColumn) { c.Index = "index" }),
		col("bio", "text", func(c *NewColumn) { c.Index = "fulltext" }),
		col("updated", "timestamp", func(c *NewColumn) {
			c.DefaultKind = DefaultExpression
			c.Default = "CURRENT_TIMESTAMP"
			c.OnUpdateNow = true
		}),
	}
	my, err := BuildCreateTable(Dialect{kind: model.DriverMariaDB}, "shop", NewTable{Name: "users", Columns: cols, Engine: "InnoDB", Charset: "utf8mb4", Collation: "utf8mb4_unicode_ci"})
	want := "CREATE TABLE `shop`.`users` (\n" +
		"  `id` int unsigned NOT NULL AUTO_INCREMENT,\n" +
		"  `email` varchar(190) COLLATE utf8mb4_bin NOT NULL,\n" +
		"  `city` varchar(80),\n" +
		"  `bio` text,\n" +
		"  `updated` timestamp DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,\n" +
		"  PRIMARY KEY (`id`),\n" +
		"  UNIQUE KEY `users_email_key` (`email`),\n" +
		"  KEY `users_city_idx` (`city`),\n" +
		"  FULLTEXT KEY `users_bio_ft` (`bio`)\n" +
		") ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;"
	if err != nil || len(my) != 1 || my[0] != want {
		t.Fatalf("mariadb %v:\n%s\nwant\n%s", err, strings.Join(my, "\n"), want)
	}

	pgCols := []NewColumn{col("id", "bigint", pk, auto), col("email", "text", func(c *NewColumn) { c.Index = "unique"; c.Collation = "C" }),
		col("city", "text", func(c *NewColumn) { c.Index = "index" })}
	pg, err := BuildCreateTable(Dialect{kind: model.DriverPostgres}, "public", NewTable{Name: "users", Columns: pgCols})
	if err != nil || len(pg) != 2 || !strings.Contains(pg[0], `"email" text COLLATE "C",`) ||
		!strings.Contains(pg[0], `CONSTRAINT "users_email_key" UNIQUE ("email")`) || pg[1] != `CREATE INDEX "users_city_idx" ON "public"."users" ("city");` {
		t.Fatalf("postgres %v:\n%s", err, strings.Join(pg, "\n"))
	}

	sq, err := BuildCreateTable(Dialect{kind: model.DriverSQLite}, "main", NewTable{Name: "t", Strict: true,
		Columns: []NewColumn{col("id", "INTEGER", pk, auto), col("n", "TEXT", func(c *NewColumn) { c.Collation = "NOCASE"; c.Index = "index" })}})
	if err != nil || !strings.HasSuffix(sq[0], ") STRICT;") || !strings.Contains(sq[0], `"n" TEXT COLLATE NOCASE`) || sq[1] != `CREATE INDEX "t_n_idx" ON "t" ("n");` {
		t.Fatalf("sqlite %v:\n%s", err, strings.Join(sq, "\n"))
	}

	bad := []struct {
		d    model.Driver
		t    NewTable
		want string
	}{
		{model.DriverSQLite, NewTable{Name: "t", Strict: true, Columns: []NewColumn{col("a", "varchar(10)")}}, "STRICT table only allows"},
		{model.DriverPostgres, NewTable{Name: "t", Strict: true, Columns: []NewColumn{col("a", "text")}}, "SQLite feature"},
		{model.DriverPostgres, NewTable{Name: "t", Columns: []NewColumn{col("a", "text", func(c *NewColumn) { c.Index = "fulltext" })}}, "FULLTEXT"},
		{model.DriverPostgres, NewTable{Name: "t", Engine: "InnoDB", Columns: []NewColumn{col("a", "text")}}, "MySQL/MariaDB table option"},
		{model.DriverMySQL, NewTable{Name: "t", Engine: "Inno DB", Columns: []NewColumn{col("a", "text")}}, "isn't a storage engine"},
		{model.DriverMySQL, NewTable{Name: "t", Columns: []NewColumn{col("a", "text", func(c *NewColumn) { c.OnUpdateNow = true })}}, "DATETIME or TIMESTAMP"},
		{model.DriverPostgres, NewTable{Name: "t", Columns: []NewColumn{col("a", "timestamp", func(c *NewColumn) { c.OnUpdateNow = true })}}, "only available on MySQL"},
		{model.DriverMySQL, NewTable{Name: "t", Columns: []NewColumn{col("a", "text", func(c *NewColumn) { c.Collation = "x'; DROP" })}}, "isn't a collation"},
	}
	for _, b := range bad {
		if _, err := BuildCreateTable(Dialect{kind: b.d}, "s", b.t); err == nil || !strings.Contains(err.Error(), b.want) {
			t.Errorf("%s %+v: got %v, want %q", b.d, b.t, err, b.want)
		}
	}
}

func TestBuildCreateDatabase(t *testing.T) {
	cases := []struct {
		d    model.Driver
		nd   NewDatabase
		want string
	}{
		{model.DriverPostgres, NewDatabase{Name: "shop"}, `CREATE DATABASE "shop";`},
		{model.DriverPostgres, NewDatabase{Name: "sales", Kind: "schema"}, `CREATE SCHEMA "sales";`},
		{model.DriverMySQL, NewDatabase{Name: "shop", Charset: "utf8mb4"}, "CREATE DATABASE `shop` CHARACTER SET utf8mb4;"},
		{model.DriverMariaDB, NewDatabase{Name: "we`ird"}, "CREATE DATABASE `we``ird`;"},
	}
	for _, c := range cases {
		if got, err := BuildCreateDatabase(Dialect{kind: c.d}, c.nd); err != nil || got != c.want {
			t.Errorf("%s %+v: %q %v", c.d, c.nd, got, err)
		}
	}
	for _, c := range []struct {
		d  model.Driver
		nd NewDatabase
	}{
		{model.DriverSQLite, NewDatabase{Name: "x"}},
		{model.DriverPostgres, NewDatabase{Name: ""}},
		{model.DriverMySQL, NewDatabase{Name: "x", Charset: "utf8; DROP"}},
		{model.DriverMySQL, NewDatabase{Name: "x", Kind: "schema"}},
	} {
		if _, err := BuildCreateDatabase(Dialect{kind: c.d}, c.nd); err == nil {
			t.Errorf("%s %+v should fail", c.d, c.nd)
		}
	}
}
