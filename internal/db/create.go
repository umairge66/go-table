// NewColumn is a column of a table being created.
type NewColumn struct {
	ColumnDef
	PrimaryKey bool `json:"primaryKey"`
	// AutoIncrement numbers new rows: an identity column on PostgreSQL,
	// AUTO_INCREMENT on MySQL/MariaDB, INTEGER PRIMARY KEY AUTOINCREMENT on
	// SQLite.
	AutoIncrement bool `json:"autoIncrement"`
	// Index adds a single-column "unique", "index" or (MySQL/MariaDB)
	// "fulltext" index. Several PrimaryKey columns make one composite key.
	Index string `json:"index"`
}

// NewTable describes a table to create.
type NewTable struct {
	Name    string      `json:"name"`
	Columns []NewColumn `json:"columns"`
	Comment string      `json:"comment"`
	// MySQL/MariaDB table options.
	Engine    string `json:"engine"`
	Charset   string `json:"charset"`
	Collation string `json:"collation"`
	// Strict makes a SQLite STRICT table (types are enforced).
	Strict bool `json:"strict"`
}

var (
	pgIdentityType = regexp.MustCompile(`(?i)^(smallint|integer|int|bigint|int2|int4|int8)$`)
	mysqlIntType   = regexp.MustCompile(`(?i)^(tinyint|smallint|mediumint|int|integer|bigint)(\s*\(\s*\d+\s*\))?(\s+unsigned)?(\s+zerofill)?$`)
	sqliteLiteral  = regexp.MustCompile(`(?i)^([+-]?\d+(\.\d+)?|'([^']|'')*'|null|true|false|current_(timestamp|date|time))$`)
	sqliteStrict   = regexp.MustCompile(`(?i)^(int|integer|real|text|blob|any)$`)
	optionName     = regexp.MustCompile(`^[A-Za-z0-9_]+$`)
)

// indexName builds a readable index name within PostgreSQL's 63 bytes.
func indexName(table, col, suffix string) string {
	n := table + "_" + col + "_" + suffix
	if len(n) > 63 {
		n = n[:63-len(suffix)-1] + "_" + suffix
	}
	return n
}

// BuildCreateTable returns CREATE TABLE plus what can't go inside it:
// CREATE INDEX (PostgreSQL, SQLite) and COMMENT ON (PostgreSQL).
func BuildCreateTable(d Dialect, schema string, t NewTable) ([]string, error) {
	name := strings.TrimSpace(t.Name)
	if name == "" {
		return nil, errors.New("table name is required")
	}
	if len(t.Columns) == 0 {
		return nil, errors.New("add at least one column")
	}
	seen := map[string]bool{}
	var pk []string
	autos := 0
	for i, c := range t.Columns {
		n := strings.TrimSpace(c.Name)
		if err := c.check(d, true); err != nil {
			if n == "" {
				n = fmt.Sprintf("%d", i+1)
			}
			return nil, fmt.Errorf("column %s: %w", n, err)
		}
		if c.Position != "" {
			return nil, fmt.Errorf("column %s: position only applies when adding a column", n)
		}
		if seen[strings.ToLower(n)] {
			return nil, fmt.Errorf("column %q appears twice", n)
		}
		seen[strings.ToLower(n)] = true
		if c.PrimaryKey {
			pk = append(pk, n)
		}
		switch c.Index {
		case "", "unique", "index":
		case "fulltext":
			if !d.mysqlLike() {
				return nil, fmt.Errorf("column %s: FULLTEXT indexes are a MySQL/MariaDB feature", n)
			}
		default:
			return nil, fmt.Errorf("column %s: unknown index %q", n, c.Index)
		}
		if c.AutoIncrement {
			autos++
			if c.DefaultKind != DefaultNone {
				return nil, fmt.Errorf("column %s: an auto-increment column can't have a default", n)
			}
		}
		if t.Strict && d.kind == model.DriverSQLite && !sqliteStrict.MatchString(strings.TrimSpace(c.Type)) {
			return nil, fmt.Errorf("column %s: a STRICT table only allows INT, INTEGER, REAL, TEXT, BLOB or ANY", n)
		}
	}
	if autos > 1 {
		return nil, errors.New("only one column can auto-increment")
	}
	if t.Strict && d.kind != model.DriverSQLite {
		return nil, errors.New("STRICT tables are a SQLite feature")
	}
	for _, o := range []struct{ label, v string }{{"storage engine", t.Engine}, {"character set", t.Charset}, {"collation", t.Collation}} {
		if o.v == "" {
			continue
		}
		if !d.mysqlLike() {
			return nil, fmt.Errorf("the %s is a MySQL/MariaDB table option", o.label)
		}
		if !optionName.MatchString(o.v) {
			return nil, fmt.Errorf("%q isn't a %s name", o.v, o.label)
		}
	}

	ref := TableRef{Schema: schema, Name: name}
	var lines, after []string
	inlinePK := false
	for _, c := range t.Columns {
		n := strings.TrimSpace(c.Name)
		typ := strings.TrimSpace(c.Type)
		extra := ""
		if c.AutoIncrement {
			switch {
			case d.kind == model.DriverPostgres:
				if !pgIdentityType.MatchString(typ) {
					return nil, fmt.Errorf("column %s: auto-increment needs an integer type (integer or bigint)", n)
				}
				extra = " GENERATED BY DEFAULT AS IDENTITY"
			case d.mysqlLike():
				if !mysqlIntType.MatchString(typ) {
					return nil, fmt.Errorf("column %s: auto-increment needs an integer type (int or bigint)", n)
				}
				if !c.PrimaryKey && c.Index != "unique" && c.Index != "index" {
					return nil, fmt.Errorf("column %s: on MySQL and MariaDB an auto-increment column must be the primary key or indexed", n)
				}
				extra = " AUTO_INCREMENT"
			case d.kind == model.DriverSQLite:
				// SQLite only numbers rows for a single INTEGER PRIMARY KEY.
				if !strings.EqualFold(typ, "integer") || !c.PrimaryKey || len(pk) != 1 {
					return nil, fmt.Errorf("column %s: on SQLite only a single INTEGER primary key can auto-increment", n)
				}
				extra = " PRIMARY KEY AUTOINCREMENT"
				inlinePK = true
			}
		}
		if extra != "" && d.kind != model.DriverSQLite {
			// AUTO_INCREMENT / identity sit after NOT NULL; SQLite's goes first.
			lines = append(lines, columnSQL(d, c.ColumnDef, !c.Nullable || c.PrimaryKey, extra))
		} else if extra != "" {
			def := c.ColumnDef
			def.Type = typ + extra
			lines = append(lines, columnSQL(d, def, true, ""))
		} else {
			lines = append(lines, columnSQL(d, c.ColumnDef, !c.Nullable || c.PrimaryKey, ""))
		}
		if strings.TrimSpace(c.Comment) != "" && d.kind == model.DriverSQLite {
			return nil, errors.New("SQLite doesn't support column comments")
		}
	}
	if len(pk) > 0 && !inlinePK {
		q := make([]string, len(pk))
		for i, p := range pk {
			q[i] = d.QuoteIdent(p)
		}
		lines = append(lines, "PRIMARY KEY ("+strings.Join(q, ", ")+")")
	}
	for _, c := range t.Columns {
		n := strings.TrimSpace(c.Name)
		qn := d.QuoteIdent(n)
		switch {
		case c.Index == "unique":
			if d.mysqlLike() {
				lines = append(lines, "UNIQUE KEY "+d.QuoteIdent(indexName(name, n, "key"))+" ("+qn+")")
			} else {
				lines = append(lines, "CONSTRAINT "+d.QuoteIdent(indexName(name, n, "key"))+" UNIQUE ("+qn+")")
			}
		case c.Index == "fulltext":
			lines = append(lines, "FULLTEXT KEY "+d.QuoteIdent(indexName(name, n, "ft"))+" ("+qn+")")
		case c.Index == "index" && d.mysqlLike():
			lines = append(lines, "KEY "+d.QuoteIdent(indexName(name, n, "idx"))+" ("+qn+")")
		case c.Index == "index":
			idx := TableRef{Schema: schema, Name: indexName(name, n, "idx")}
			if d.kind == model.DriverPostgres {
				// PostgreSQL index names belong to the table's schema implicitly.
				after = append(after, fmt.Sprintf("CREATE INDEX %s ON %s (%s);", d.QuoteIdent(idx.Name), d.QualifiedName(ref), qn))
			} else {
				after = append(after, fmt.Sprintf("CREATE INDEX %s ON %s (%s);", d.QualifiedName(idx), d.QuoteIdent(name), qn))
			}
		}
	}
	stmt := "CREATE TABLE " + d.QualifiedName(ref) + " (\n  " + strings.Join(lines, ",\n  ") + "\n)"
	comment := strings.TrimSpace(t.Comment)
	if d.mysqlLike() {
		var opts []string
		if t.Engine != "" {
			opts = append(opts, "ENGINE="+t.Engine)
		}
		if t.Charset != "" {
			opts = append(opts, "DEFAULT CHARSET="+t.Charset)
		}
		if t.Collation != "" {
			opts = append(opts, "COLLATE="+t.Collation)
		}
		if comment != "" {
			opts = append(opts, "COMMENT="+d.QuoteLiteral(Text(comment)))
		}
		if len(opts) > 0 {
			stmt += " " + strings.Join(opts, " ")
		}
	} else if comment != "" && d.kind == model.DriverSQLite {
		return nil, errors.New("SQLite doesn't support table comments")
	}
	if t.Strict {
		stmt += " STRICT"
	}
	out := append([]string{stmt + ";"}, after...)
	if d.kind == model.DriverPostgres {
		if comment != "" {
			out = append(out, fmt.Sprintf("COMMENT ON TABLE %s IS %s;", d.QualifiedName(ref), d.QuoteLiteral(Text(comment))))
		}
		for _, c := range t.Columns {
			if cm := strings.TrimSpace(c.Comment); cm != "" {
				out = append(out, fmt.Sprintf("COMMENT ON COLUMN %s.%s IS %s;", d.QualifiedName(ref), d.QuoteIdent(strings.TrimSpace(c.Name)), d.QuoteLiteral(Text(cm))))
			}
		}
	}
	return out, nil
}

// CreateTable creates a table (in one transaction where the database allows).
func (c *Conn) CreateTable(ctx context.Context, schema string, t NewTable) ([]string, error) {
	stmts, err := BuildCreateTable(c.Dialect, schema, t)
	if err != nil {
		return nil, err
	}
	return stmts, c.runDDL(ctx, stmts)
}

// NewDatabase describes a database (or PostgreSQL schema) to create.
type NewDatabase struct {
	Name string `json:"name"`
	// Kind is "database" or, on PostgreSQL, "schema".
	Kind string `json:"kind"`
	// Charset is MySQL/MariaDB's default character set, e.g. utf8mb4.
	Charset string `json:"charset"`
}

var charsetPattern = regexp.MustCompile(`^[A-Za-z0-9_]+$`)

// BuildCreateDatabase returns CREATE DATABASE / CREATE SCHEMA.
func BuildCreateDatabase(d Dialect, nd NewDatabase) (string, error) {
	name := strings.TrimSpace(nd.Name)
	if name == "" {
		return "", errors.New("database name is required")
	}
	switch d.kind {
	case model.DriverSQLite:
		return "", errors.New("SQLite keeps one database per file; create a new database file instead")
	case model.DriverPostgres:
		switch nd.Kind {
		case "", "database":
			return "CREATE DATABASE " + d.QuoteIdent(name) + ";", nil
		case "schema":
			return "CREATE SCHEMA " + d.QuoteIdent(name) + ";", nil
		}
		return "", fmt.Errorf("unknown kind %q", nd.Kind)
	}
	if nd.Kind == "schema" {
		return "", errors.New("on MySQL and MariaDB a schema is a database")
	}
	stmt := "CREATE DATABASE " + d.QuoteIdent(name)
	if cs := strings.TrimSpace(nd.Charset); cs != "" {
		if !charsetPattern.MatchString(cs) {
			return "", fmt.Errorf("%q isn't a character set name", cs)
		}
		stmt += " CHARACTER SET " + cs
	}
	return stmt + ";", nil
}

// CreateDatabase creates a database or schema. CREATE DATABASE can't run
// inside a transaction on PostgreSQL, so it runs on its own.
func (c *Conn) CreateDatabase(ctx context.Context, nd NewDatabase) (string, error) {
	stmt, err := BuildCreateDatabase(c.Dialect, nd)
	if err != nil {
		return "", err
	}
	if err := c.lock(ctx); err != nil {
		return "", err
	}
	defer c.mu.Unlock()
	_, err = c.conn.ExecContext(ctx, stmt)
	return stmt, err
}

// TypeInfo is what the table designer offers beyond the built-in types.
type TypeInfo struct {
	// CustomTypes are user types visible in the schema (PostgreSQL enums,
	// domains and extension types such as citext).
	CustomTypes []string `json:"customTypes"`
	Collations  []string `json:"collations"`
	// MySQL/MariaDB.
	Charsets         []string `json:"charsets"`
	Engines          []string `json:"engines"`
	DefaultEngine    string   `json:"defaultEngine"`
	DefaultCharset   string   `json:"defaultCharset"`
	DefaultCollation string   `json:"defaultCollation"`
	// Strict reports SQLite STRICT table support (3.37+).
	Strict bool `json:"strict"`
}

// TypeInfo reads the type-related options of schema from the server.
func (c *Conn) TypeInfo(ctx context.Context, schema string) (*TypeInfo, error) {
	if err := c.lock(ctx); err != nil {
		return nil, err
	}
	defer c.mu.Unlock()
	info := &TypeInfo{CustomTypes: []string{}, Collations: []string{}, Charsets: []string{}, Engines: []string{}}
	var err error
	switch {
	case c.Dialect.kind == model.DriverPostgres:
		// Types in this schema or public (found without qualifying them);
		// skip array types (_name) and table row types.
		info.CustomTypes, err = c.queryStrings(ctx, `SELECT DISTINCT t.typname FROM pg_type t
			JOIN pg_namespace n ON n.oid = t.typnamespace
			WHERE n.nspname IN ($1, 'public') AND t.typtype IN ('e', 'd', 'b') AND t.typname NOT LIKE '\_%'
			AND (t.typrelid = 0) ORDER BY 1`, schema)
		if err == nil {
			info.Collations, err = c.queryStrings(ctx, `SELECT collname FROM pg_collation
				WHERE collencoding IN (-1, pg_char_to_encoding(current_setting('server_encoding'))) ORDER BY collname <> 'C', collname <> 'POSIX', collname`)
		}
	case c.Dialect.mysqlLike():
		if info.Charsets, err = c.queryStrings(ctx, "SELECT CHARACTER_SET_NAME FROM information_schema.CHARACTER_SETS ORDER BY 1"); err != nil {
			break
		}
		// MariaDB 10.10+ lists character-set-independent collations (uca1400)
		// without a character set; their full names are in this view.
		info.Collations, err = c.queryStrings(ctx, "SELECT DISTINCT FULL_COLLATION_NAME FROM information_schema.COLLATION_CHARACTER_SET_APPLICABILITY ORDER BY 1")
		if err != nil {
			if info.Collations, err = c.queryStrings(ctx, "SELECT COLLATION_NAME FROM information_schema.COLLATIONS WHERE CHARACTER_SET_NAME IS NOT NULL ORDER BY 1"); err != nil {
				break
			}
		}
		rows, qerr := c.conn.QueryContext(ctx, "SELECT ENGINE, SUPPORT FROM information_schema.ENGINES WHERE SUPPORT IN ('YES', 'DEFAULT') ORDER BY ENGINE")
		if qerr != nil {
			err = qerr
			break
		}
		for rows.Next() {
			var e, support string
			if rows.Scan(&e, &support) == nil {
				info.Engines = append(info.Engines, e)
				if support == "DEFAULT" {
					info.DefaultEngine = e
				}
			}
		}
		rows.Close()
		err = c.conn.QueryRowContext(ctx, "SELECT DEFAULT_CHARACTER_SET_NAME, DEFAULT_COLLATION_NAME FROM information_schema.SCHEMATA WHERE SCHEMA_NAME = ?", schema).
			Scan(&info.DefaultCharset, &info.DefaultCollation)
		if errors.Is(err, sql.ErrNoRows) {
			err = nil
		}
	case c.Dialect.kind == model.DriverSQLite:
		info.Collations = []string{"BINARY", "NOCASE", "RTRIM"}
		var v string
		if c.conn.QueryRowContext(ctx, "SELECT sqlite_version()").Scan(&v) == nil {
			var maj, min int
			fmt.Sscanf(v, "%d.%d", &maj, &min)
			info.Strict = maj > 3 || maj == 3 && min >= 37
		}
	}
	return info, err
}
